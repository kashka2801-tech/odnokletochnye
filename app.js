const chips=document.getElementById('orgChips'), stage=document.getElementById('stage'), info=document.getElementById('info');
let current='amoeba';
Object.entries(organisms).forEach(([k,o])=>{
  const b=document.createElement('button');
  b.className='chip'; b.textContent=o.name; b.setAttribute('aria-pressed', k===current);
  b.onclick=()=>{current=k; draw(); [...chips.children].forEach(c=>c.setAttribute('aria-pressed', c===b));};
  chips.appendChild(b);
});
function draw(){
  const o=organisms[current];
  stage.innerHTML=`<svg class="organism" viewBox="-40 -10 480 320" role="img" aria-label="Схема: ${o.name}">${o.svg}
    ${o.parts.map((p,i)=>`<g class="hot" data-i="${i}" tabindex="0" role="button" aria-label="${p.t}">
      <line class="lead" x1="${p.x}" y1="${p.y}" x2="${p.x+(p.lx||0)}" y2="${p.y+(p.ly||-18)+((p.ly||-18)<0?4:-10)}"/>
      <circle class="dot" cx="${p.x}" cy="${p.y}" r="8"/>
      <text x="${p.x+(p.lx||0)}" y="${p.y+(p.ly||-18)}" text-anchor="${(p.lx||0)<-8?'end':((p.lx||0)>8?'start':'middle')}">${p.s||p.t}</text>
    </g>`).join('')}</svg>`;
  info.innerHTML=`<span class="badge">${o.name}</span><h3>Нажми точку на схеме</h3><p style="margin:0">${o.sub}</p>`;
  stage.querySelectorAll('.hot').forEach(g=>{
    const show=()=>{
      stage.querySelectorAll('.hot').forEach(x=>x.classList.remove('on')); g.classList.add('on');
      const p=o.parts[+g.dataset.i];
      info.innerHTML=`<span class="badge">${o.name}</span><h3>${p.t}</h3><p style="margin:0">${p.d}</p>`;
    };
    g.onclick=show; g.onkeydown=e=>{if(e.key==='Enter'||e.key===' '){e.preventDefault();show();}};
  });
}
draw();

