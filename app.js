const quizEl=document.getElementById('quiz'), bar=document.getElementById('bar'),
      res=document.getElementById('result'), scoreText=document.getElementById('scoreText'), verdict=document.getElementById('verdict');
let answered=0, score=0;
function buildQuiz(){
  answered=0;score=0;bar.style.width='0';res.classList.add('hidden');
  quizEl.innerHTML=qs.map((q,i)=>`<div class="q"><h3>${i+1}. ${q[0]}</h3><div class="opts">${
    q[1].map((o,j)=>`<button class="opt" data-q="${i}" data-o="${j}">${o}</button>`).join('')
  }</div><p class="explain hidden" id="e${i}">${q[3]}</p></div>`).join('');
  quizEl.querySelectorAll('.opt').forEach(b=>b.onclick=()=>{
    const i=+b.dataset.q, j=+b.dataset.o, correct=qs[i][2];
    const group=quizEl.querySelectorAll(`.opt[data-q="${i}"]`);
    if([...group].some(x=>x.disabled)) return;
    group.forEach(x=>{x.disabled=true; if(+x.dataset.o===correct)x.classList.add('right');});
    if(j!==correct) b.classList.add('wrong'); else score++;
    document.getElementById('e'+i).classList.remove('hidden');
    answered++; bar.style.width=(answered/qs.length*100)+'%';
    if(answered===qs.length) finish();
  });
}
function finish(){
  res.classList.remove('hidden');
  scoreText.textContent=`Результат: ${score} из ${qs.length}`;
  verdict.textContent = score>=11 ? 'Отлично! Тема освоена — можно переходить к многоклеточным животным.'
    : score>=8 ? 'Хорошо. Повтори вкладку «Сравнение» — там самые частые ловушки.'
    : score>=5 ? 'Неплохое начало. Пройди «Атлас строения» и «Процессы жизни» ещё раз.'
    : 'Стоит начать с раздела «Что это такое», а потом вернуться к тесту.';
  res.scrollIntoView({behavior:'smooth',block:'center'});
}
document.getElementById('again').onclick=()=>{buildQuiz();quizEl.scrollIntoView({behavior:'smooth'});};
buildQuiz();
